def icon(name: str, label: str = "") -> Markup:
    """Return one icon as an inline SVG element.

    Args:
        name: Octicon name, for example "git-merge". It must be in `_ICONS`.
        label: Text for screen readers. Empty means the icon is decoration only.

    Raises:
        KeyError: The name is not one of the copied icons. A typo in a template
            then fails in the tests, not as a missing icon on a page.
    """
    width, body = _ICONS[name]
    if label:
        a11y = Markup(' role="img" aria-label="{}"').format(label)
    else:
        a11y = Markup(' aria-hidden="true"')
    return Markup(
        '<svg class="octicon octicon-{}" width="{}" height="16" viewBox="0 0 {} 16"'
        ' fill="currentColor"{}>{}</svg>'
    ).format(name, width, width, a11y, Markup(body))
